  static String tr(String key) {
    final lang = appLanguage.value;
    return _localizedValues[lang]?[key] ?? _localizedValues['ru']![key] ?? key;
  }

  static Future<String> translateUserContent(String text) async {
    if (text.trim().isEmpty) return text;
    try {
      final currentLang = appLanguage.value;
      final res = await ApiClient.instance.post('/translate', body: {
        'text': text,
        'targetLang': currentLang,
      });
      if (res is Map<String, dynamic> && res['translatedText'] is String) {
        return res['translatedText'] as String;
      }
      return text;
    } catch (_) {
      return text;
    }
  }

  static Future<void> changeLanguage(String langCode) async {
    appLanguage.value = langCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('saved_lang', langCode);
  }
